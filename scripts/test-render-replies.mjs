import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";

const html=readFileSync(new URL("../worker/index.html",import.meta.url),"utf8");
const source=html.match(/function cleanAiBody\(text\)[\s\S]*?\r?\nfunction pushMsg\(/)?.[0].replace(/\r?\nfunction pushMsg\($/,'');
assert.ok(source,"render reply parser missing");
const context=vm.createContext({MOTIF_PATHS:{},libraryAssets:[],PAGE_W:794,page:()=>({}),pageHeight:()=>1123});
vm.runInContext(source,context);
const parse=raw=>vm.runInContext(`parseAiReply(${JSON.stringify(raw)},false,[],false,false,false,new Set())`,context);
const toolCall='<tool_call>terminal<param_key>command</param_key><param_value>echo "skip"</param_value></tool_call>';
assert.match(parse(toolCall).error,/工具指令/);
assert.match(parse("我现在来设计一下。若要使用终端请告诉我。").error,/未生成可预览/);
const question=parse("你希望以紫色还是蓝色为主？");
assert.equal(question.spec,null);
assert.equal(question.error,undefined);
const valid=parse('好的。```json\n{"background":{"type":"solid","color":"#ffffff"},"decorations":[],"layers":[]}\n```');
assert.ok(valid.spec);
assert.equal(valid.error,undefined);
const shapePlan='```json\n{"background":{"type":"solid","color":"#ffffff"},"decorations":[{"type":"star"}],"layers":[{"type":"shape","shape":"ellipse","fill":"#aabbcc","x":20,"y":20,"w":200,"h":200}]}\n```';
const repaired=parse('<tool_call>terminal<param_key>command</param_key><param_value>echo skip</param_value></tool_call>'+shapePlan);
assert.ok(repaired.spec);
assert.equal(repaired.spec.decorations.length,0);
assert.doesNotMatch(repaired.body,/tool_call|star/);
context.libraryAssets=[{id:"a"},{id:"b"}];
const multiRemix=vm.runInContext(`parseAiReply(${JSON.stringify(JSON.stringify({background:{type:"solid",color:"#ffffff"},layers:[{type:"image",assetId:"a",remix:"illustration",x:20,y:20,w:260,h:260},{type:"image",assetId:"b",remix:"comic",x:320,y:20,w:260,h:260}]}))},false,[],true,false,false,new Set(["a","b"]))`,context);
assert.equal(multiRemix.error,undefined);
assert.equal(multiRemix.spec.layers.filter(layer=>layer.remix).length,1);
context.MOTIF_PATHS.star="M50 5 L95 95 L5 95 Z";
const editableMotif=parse(JSON.stringify({background:{type:"solid",color:"#ffffff"},layers:[{type:"shape",shape:"motif",motif:"star",fill:"#e7d8f2",x:40,y:70,w:60,h:60}]}));
assert.equal(editableMotif.spec.layers[0].motif,"star");
console.log("render reply contract checks passed");
